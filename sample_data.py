"""Synthetic sample data for the imbalance price forecasting demo.

****************************************************************************
THIS IS NOT REAL MARKET DATA.
The numbers are generated by the formulas below. They imitate the *shape* of
Finnish power system data (daily patterns, wind/solar behaviour, imbalance
price spikes) so the pipeline and dashboard can be built and tested end to
end. Any metric computed on this data says something about the *code*, not
about real forecasting skill.
****************************************************************************

Why synthetic? See README.md ("What data this demo uses"). In short: the
hackathon starter package (incl. the licensed Nord Pool spot series) was only
available on sinceai.app during the event and may not be redistributed, and
Fingrid open data needs a free personal API key (see fingrid_data.py).

The generator mirrors the challenge set-up in the official briefing:
  - 15-minute resolution, timestamps in UTC
  - training period 1 Jun - 4 Oct 2026, test period 5 Oct - 1 Nov 2026
  - series: imbalance price (target), spot price, wind/solar/consumption
    day-ahead forecasts + actuals, cross-border flows, mFRR direction
  - imbalance price follows the post-1-June-2026 rule: it sits above spot
    when up-regulation dominates, below spot when down-regulation dominates,
    and near spot when there is no dominating direction
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"
SAMPLE_CSV = DATA_DIR / "sample_inputs.csv"

START = "2026-06-01T00:00:00Z"
END = "2026-11-03T00:00:00Z"  # exclusive
SEED = 42

# How long after a quarter-hour its *actual* values are published (simplified
# version of the challenge's first_usable_origin_utc rule). Day-ahead series
# (spot and the Fingrid day-ahead forecasts) are handled separately in
# features.py, because their availability depends on the delivery day.
ACTUALS_DELAY = pd.Timedelta(hours=1)
SPOT_PUBLISH_OFFSET = pd.Timedelta(hours=13)  # delivery day 00:00 minus 13h = day before 11:00 UTC
FORECAST_PUBLISH_OFFSET = pd.Timedelta(hours=14)  # day before 10:00 UTC


def _ar1(n: int, phi: float, sigma: float, rng: np.random.Generator) -> np.ndarray:
    x = np.zeros(n)
    e = rng.normal(0.0, sigma, n)
    for i in range(1, n):
        x[i] = phi * x[i - 1] + e[i]
    return x


def make_sample_data(seed: int = SEED) -> pd.DataFrame:
    """Build the synthetic dataset as a wide DataFrame indexed by UTC quarter-hour."""
    rng = np.random.default_rng(seed)
    idx = pd.date_range(START, END, freq="15min", inclusive="left", tz="UTC")
    n = len(idx)
    hour = (idx.hour + idx.minute / 60.0).to_numpy()
    dow = idx.dayofweek.to_numpy()
    doy = idx.dayofyear.to_numpy()

    # --- Day-ahead spot price (EUR/MWh) ---
    daily = 45 + 30 * np.exp(-((hour - 9) ** 2) / 8) + 35 * np.exp(-((hour - 18) ** 2) / 6)
    weekly = np.where(dow >= 5, -18, 0)
    seasonal = 15 * np.sin(2 * np.pi * (doy - 300) / 365)  # rises toward winter
    spot = daily + weekly + seasonal + _ar1(n, 0.92, 6.0, rng) * 2.2
    neg = rng.random(n) < 0.01
    spot[neg] = -rng.uniform(0, 15, neg.sum())
    sp = rng.random(n) < 0.008
    spot[sp] += rng.uniform(80, 200, sp.sum())

    # --- Wind power (MW) ---
    wl = _ar1(n, 0.985, 0.09, rng)
    wind_cf = 1 / (1 + np.exp(-(wl * 2.4))) * 0.9  # capacity factor 0..0.9
    wind_actual = 7500 * wind_cf
    wind_forecast = np.clip(wind_actual + rng.normal(0, 320, n), 0, 7500)

    # --- Solar power (MW), Helsinki-like daylight ---
    daylen = 12 + 6.5 * np.cos(2 * np.pi * (doy - 172) / 365)
    sunrise, sunset = 12 - daylen / 2, 12 + daylen / 2
    sol_pos = np.clip(np.sin(np.pi * (hour - sunrise) / daylen), 0, None)
    clouds = np.clip(rng.normal(0.75, 0.2, n), 0.05, 1)
    solar_actual = 1100 * sol_pos * clouds
    solar_forecast = np.clip(1100 * sol_pos * np.clip(clouds + rng.normal(0, 0.12, n), 0, 1), 0, None)

    # --- Consumption (MW), rising toward winter ---
    cons_base = 5200 + 1700 * (doy - 152) / 155
    cons_daily = (
        500 * np.exp(-((hour - 8) ** 2) / 10)
        + 700 * np.exp(-((hour - 18) ** 2) / 8)
        - 350 * np.exp(-((hour - 4) ** 2) / 8)
    )
    cons = cons_base + cons_daily + np.where(dow >= 5, -450, 0)
    consumption_actual = cons + rng.normal(0, 120, n)
    consumption_forecast = cons + rng.normal(0, 200, n)

    # --- Cross-border flows (MW, positive = import to Finland) ---
    flow_se1 = np.clip(1500 + _ar1(n, 0.97, 120, rng), -600, 2300)
    flow_se3 = np.clip(900 + _ar1(n, 0.97, 90, rng), -500, 1300)
    flow_ee = np.clip(700 + _ar1(n, 0.97, 80, rng), -1000, 1000)

    # --- Dominating mFRR direction: 1 = up, -1 = down, 0 = none ---
    # Persistent regime process, more up-regulation in the evening ramp,
    # more down-regulation on very windy nights.
    base_p_up = 0.34 + 0.10 * np.exp(-((hour - 18) ** 2) / 8)
    base_p_up -= 0.12 * (wind_cf > 0.75) * (hour < 6)
    raw = _ar1(n, 0.995, 0.05, rng)
    p_up = np.clip(base_p_up + raw, 0.05, 0.85)
    p_down = np.clip(
        0.30 - 0.10 * np.exp(-((hour - 18) ** 2) / 8) + 0.14 * (wind_cf > 0.75) - raw * 0.7,
        0.05,
        0.85,
    )
    p_none = np.clip(1 - p_up - p_down, 0.02, None)
    z = p_up + p_down + p_none
    p_up, p_down, p_none = p_up / z, p_down / z, p_none / z
    u = rng.random(n)
    direction = np.where(u < p_up, 1, np.where(u < p_up + p_down, -1, 0))

    # --- Imbalance price (EUR/MWh), the forecast target ---
    spike_hi = (direction == 1) & (
        rng.random(n) < (0.06 + 0.10 * np.exp(-((hour - 18) ** 2) / 8) + 0.08 * (spot > 120))
    )
    spike_lo = (direction == -1) & (rng.random(n) < (0.06 + 0.10 * (wind_cf > 0.75)))
    spread = rng.lognormal(mean=np.log(12), sigma=0.5, size=n)
    imb = spot + rng.normal(0, 3, n)
    up, dn = direction == 1, direction == -1
    imb[up] = spot[up] + spread[up] + rng.uniform(2, 15, up.sum())
    imb[dn] = spot[dn] - spread[dn] - rng.uniform(2, 15, dn.sum())
    imb[spike_hi] = spot[spike_hi] + 50 + rng.uniform(5, 250, spike_hi.sum())
    imb[spike_lo] = spot[spike_lo] - 50 - rng.uniform(5, 120, spike_lo.sum())

    # --- mFRR activation prices (context series, not used as features) ---
    mfrr_up = np.where(up, imb + rng.uniform(0, 8, n), np.nan)
    mfrr_down = np.where(dn, imb - rng.uniform(0, 8, n), np.nan)

    df = pd.DataFrame(
        {
            "timestamp_utc": idx,
            "spot_fi_eur_mwh": np.round(spot, 2),
            "wind_forecast_mw": np.round(wind_forecast, 1),
            "wind_actual_mw": np.round(wind_actual, 1),
            "solar_forecast_mw": np.round(solar_forecast, 1),
            "solar_actual_mw": np.round(solar_actual, 1),
            "consumption_forecast_mw": np.round(consumption_forecast, 1),
            "consumption_actual_mw": np.round(consumption_actual, 1),
            "flow_se1_fi_mw": np.round(flow_se1, 1),
            "flow_se3_fi_mw": np.round(flow_se3, 1),
            "flow_ee_fi_mw": np.round(flow_ee, 1),
            "mfrr_up_price": np.round(mfrr_up, 2),
            "mfrr_down_price": np.round(mfrr_down, 2),
            "imbalance_price_eur_mwh": np.round(imb, 2),
            "mfrr_direction": direction.astype(int),
        }
    )
    df["spike_high"] = (df["imbalance_price_eur_mwh"] > df["spot_fi_eur_mwh"] + 50).astype(int)
    df["spike_low"] = (df["imbalance_price_eur_mwh"] < df["spot_fi_eur_mwh"] - 50).astype(int)
    return df


def load_or_create_sample_data(path: Path = SAMPLE_CSV) -> pd.DataFrame:
    """Return the sample dataset, generating and caching it on first call."""
    if path.exists():
        df = pd.read_csv(path, parse_dates=["timestamp_utc"])
        if df["timestamp_utc"].dt.tz is None:
            df["timestamp_utc"] = df["timestamp_utc"].dt.tz_localize("UTC")
        return df
    df = make_sample_data()
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    return df


if __name__ == "__main__":
    df = load_or_create_sample_data()
    print(f"Synthetic sample data ready: {len(df)} quarter-hours "
          f"({df['timestamp_utc'].min()} .. {df['timestamp_utc'].max()})")
    print("REMINDER: synthetic data, not real market data.")
